package com.braveberry.domain.model.navi

// 원본 이벤트 종류를 유지함. SDK 모델은 Domain으로 올리지 않음.
enum class NaviEventType {
    ROUTE_STARTED, ROUTE_ENDED, ROUTING_COMPLETED, REROUTE_ENDED,
    ROUTE_OPTION_CHANGED, ROUTE_CANCELLED, WAYPOINT_CHANGED,
    DESTINATION_ARRIVED, WAYPOINT_ARRIVED, ERROR, CURRENT_LOCATION,
    ROUTE_STATE, DESTINATION_INFO, WAYPOINT_INFO, RECENT_DESTINATIONS,
    BOOKMARKS, SPEED_LIMIT, CAMERA_ALERT, DRIVING_INFO,
    BOOKMARK_CHANGED, DESTINATION_CHANGED, NAVIGATION_STATUS,
    TBT_INFO, CHARGER_OPERATORS, CAUTION_POINTS, TRIP_INFO
}

data class NaviEvent(
    val type: NaviEventType,
    val detail: String? = null,
    val speedLimitKph: Int? = null
)
